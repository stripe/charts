// Generates the reference guide's table of themable CSS custom properties from the
// design tokens, so the documentation can't drift from the code:
//   node scripts/theming-table.js          checks the reference guide, exits 1 if stale
//   node scripts/theming-table.js --write  rewrites the table in the reference guide
// A property is listed when the stylesheet (or render code) reads it with
// var(), so overriding it on a chart takes effect, and layout code doesn't
// also read it as a number. Tokens that feed layout in JavaScript (label
// spacing, marker radii) are left out: overriding them in CSS would do
// nothing or disagree with the geometry.
const esbuild = require('esbuild');
const fs = require('fs');
const os = require('os');
const path = require('path');

const root = path.join(__dirname, '..');
const referencePath = path.join(root, 'docs', 'reference.md');
const START =
  '<!-- theming-table:start (generated by scripts/theming-table.js) -->';
const END = '<!-- theming-table:end -->';

/** Loads the token tree and the stylesheet text by bundling the sources. */
function loadTokensAndStylesheet() {
  const result = esbuild.buildSync({
    stdin: {
      contents:
        "export {tokens} from './src/tokens';\n" +
        "export {ensureStylesheet, tokenProperties} from './src/render/styles';\n",
      resolveDir: root,
      loader: 'ts',
    },
    bundle: true,
    platform: 'node',
    format: 'cjs',
    write: false,
    logLevel: 'warning',
  });
  const file = path.join(
    os.tmpdir(),
    `stripe-charts-theming-${process.pid}.js`,
  );
  fs.writeFileSync(file, result.outputFiles[0].text);
  // The stylesheet helper checks for shadow roots with Node's constants.
  global.Node = global.Node || {DOCUMENT_FRAGMENT_NODE: 11};
  let module;
  try {
    // The bundle is written to a temporary file so Node can load it.
    module = require(file);
  } finally {
    fs.unlinkSync(file);
  }
  // A stand-in element: ensureStylesheet only creates a <style> and appends
  // it to the document head, which is all this needs to capture.
  let css = '';
  const head = {
    querySelector: () => null,
    appendChild: (style) => {
      css = style.textContent;
    },
  };
  module.ensureStylesheet({
    getRootNode: () => ({nodeType: 9}),
    ownerDocument: {
      head,
      createElement: () => ({setAttribute() {}, textContent: ''}),
    },
  });
  return {tokens: module.tokens, css, properties: module.tokenProperties};
}

/** The TSDoc comment of each field of the `Tokens` type, by dotted path. */
function tokenDocs() {
  const source = fs.readFileSync(path.join(root, 'src', 'tokens.ts'), 'utf8');
  const start = source.indexOf('export type Tokens = {');
  const lines = source.slice(start).split('\n').slice(1);
  const docs = {};
  const stack = [];
  let pending = null;
  let docLines = null;
  for (const line of lines) {
    const text = line.trim();
    if (docLines) {
      docLines.push(text.replace(/\*\/$/, '').replace(/^\*\s?/, ''));
      if (text.endsWith('*/')) {
        pending = docLines.join(' ').trim();
        docLines = null;
      }
    } else if (text.startsWith('/**')) {
      const body = text.replace(/^\/\*\*\s?/, '');
      if (body.endsWith('*/')) pending = body.replace(/\s?\*\/$/, '').trim();
      else docLines = [body];
    } else if (text.startsWith('}')) {
      if (stack.length === 0) break;
      stack.pop();
    } else {
      const field = /^(\w+)\??:\s*(.*)$/.exec(text);
      if (field) {
        const [, key, rest] = field;
        docs[[...stack, key].join('.')] = pending;
        pending = null;
        if (rest.startsWith('{') && !rest.includes('}')) stack.push(key);
      }
    }
  }
  // TSDoc links read as code in the reference guide.
  for (const [key, doc] of Object.entries(docs)) {
    if (doc) {
      docs[key] = doc
        .replace(/\s*\(see \{@link [^}]+\}\)/g, '')
        .replace(/\{@link ([^}]+)\}/g, '`$1`');
    }
  }
  return docs;
}

function kebab(segment) {
  return segment.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/**
 * Each property's default as the docs show it: the fallback written at its
 * use sites, or for a color that follows a role, the role and its value.
 */
function defaults(properties) {
  const result = new Map();
  for (const {name, fallback} of properties) {
    const follows = /^var\((--sc-color-[a-z-]+), (.+)\)$/.exec(fallback);
    result.set(
      name,
      follows
        ? `follows \`${follows[1]}\` (\`${follows[2]}\`)`
        : `\`${fallback}\``,
    );
  }
  return result;
}

/** Token paths read through `vars.` in render code (inline styles). */
function inlinePaths() {
  const paths = new Set();
  const visit = (dir) => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(file);
      else if (/\.ts$/.test(entry.name) && !/\.test\.ts$/.test(entry.name)) {
        const source = fs.readFileSync(file, 'utf8');
        for (const match of source.matchAll(/\bvars\.([\w.]+)/g)) {
          paths.add(match[1]);
        }
      }
    }
  };
  visit(path.join(root, 'src', 'render'));
  return paths;
}

/**
 * Token paths that layout code reads as numbers from `tokens`, such as
 * marker radii and stack gaps. A CSS override of those would disagree with
 * the geometry, so they are left out even where the stylesheet reads them.
 */
function layoutPaths() {
  const paths = new Set();
  const visit = (dir) => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== 'testing') visit(file);
      } else if (/\.ts$/.test(entry.name) && !/\.test\.ts$/.test(entry.name)) {
        const source = fs.readFileSync(file, 'utf8');
        for (const match of source.matchAll(
          /const \{([^}]+)\} = tokens\.([\w.]+)/g,
        )) {
          for (const name of match[1].split(',')) {
            paths.add(`${match[2]}.${name.split(':')[0].trim()}`);
          }
        }
        const withoutDestructuring = source.replace(
          /const \{[^}]+\} = tokens\.[\w.]+/g,
          '',
        );
        for (const match of withoutDestructuring.matchAll(
          /\btokens\.([\w.]+)/g,
        )) {
          paths.add(match[1]);
        }
      }
    }
  };
  for (const dir of ['render', 'layout']) visit(path.join(root, 'src', dir));
  return paths;
}

/** Leaves of the token tree as {path, name}, in declaration order. */
function leaves(tree, prefix = []) {
  return Object.entries(tree).flatMap(([key, value]) =>
    typeof value === 'object' && value !== null && !('role' in value)
      ? leaves(value, [...prefix, key])
      : [
          {
            path: [...prefix, key],
            name: `--sc-${[...prefix, key].map(kebab).join('-')}`,
            value,
          },
        ],
  );
}

function humanize(segments) {
  return segments
    .map((segment) =>
      /^\d+$/.test(segment)
        ? `color ${Number(segment) + 1}`
        : kebab(segment).replace(/-/g, ' '),
    )
    .join(', ');
}

/** Builds the markdown: one table per top-level token group. */
function buildTable() {
  const {tokens, css, properties} = loadTokensAndStylesheet();
  const docs = tokenDocs();
  const values = defaults(properties);
  const inline = inlinePaths();
  const layout = layoutPaths();
  const readByLayout = (leaf, value) =>
    typeof value === 'number' &&
    [...layout].some(
      (layoutPath) =>
        leaf.path.join('.') === layoutPath ||
        leaf.path.join('.').startsWith(`${layoutPath}.`),
    );
  const used = (leaf) =>
    css.includes(`var(${leaf.name},`) ||
    css.includes(`var(${leaf.name})`) ||
    [...inline].some((inlinePath) =>
      leaf.path.join('.').startsWith(inlinePath),
    );
  const sections = [];
  for (const group of Object.keys(tokens)) {
    const rows = leaves(tokens[group], [group])
      .filter((leaf) => used(leaf) && !readByLayout(leaf, leaf.value))
      .map((leaf) => {
        const own = docs[leaf.path.join('.')];
        const description = own || humanize(leaf.path.slice(1));
        return `| \`${leaf.name}\` | ${values.get(
          leaf.name,
        )} | ${description} |`;
      });
    const heading = docs[group] ? ` ${docs[group]}` : '';
    if (rows.length > 0)
      sections.push(
        [
          `**\`${group}\`**:${heading}`,
          '',
          '| Property | Default | Styles |',
          '|---|---|---|',
          ...rows,
        ].join('\n'),
      );
  }
  return sections.join('\n\n');
}

function main() {
  const readme = fs.readFileSync(referencePath, 'utf8');
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) {
    process.stderr.write(`docs/reference.md has no ${START} ... ${END} block\n`);
    process.exit(1);
  }
  const table = buildTable();
  const updated = `${readme.slice(
    0,
    start + START.length,
  )}\n\n${table}\n\n${readme.slice(end)}`;
  // Every property the reference guide mentions elsewhere, for example in the dark
  // theme example, must be one the table lists.
  const listed = new Set(table.match(/--sc-[a-z0-9-]*[a-z0-9]/g));
  // Wildcards such as `--sc-color-*` name a family, not one property.
  const prose = (readme.slice(0, start) + readme.slice(end)).replace(
    /--sc-[a-z0-9-]*\*/g,
    '',
  );
  const unknown = [
    ...new Set(prose.match(/--sc-[a-z0-9-]*[a-z0-9]/g) || []),
  ].filter((name) => !listed.has(name));
  if (unknown.length > 0) {
    process.stderr.write(
      `docs/reference.md mentions properties that aren't themable: ${unknown.join(
        ', ',
      )}\n`,
    );
    process.exit(1);
  }
  if (process.argv.includes('--write')) {
    fs.writeFileSync(referencePath, updated);
    process.stdout.write('docs/reference.md theming table updated\n');
  } else if (updated !== readme) {
    process.stderr.write(
      'docs/reference.md theming table is out of date; run node scripts/theming-table.js --write\n',
    );
    process.exit(1);
  } else {
    process.stdout.write('docs/reference.md theming table is up to date\n');
  }
}

main();
